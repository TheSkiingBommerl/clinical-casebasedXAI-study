import streamlit as st
import plotly.graph_objects as go
import pandas as pd
from collections import Counter

LEADS = ["DI", "DII", "DIII", "AVR", "AVL", "AVF", "V1", "V2", "V3", "V4", "V5", "V6"]
LEAD_NAMES = ["DI", "DII", "DIII", "aVR", "aVL", "aVF", "V1", "V2", "V3", "V4", "V5", "V6"]

@st.cache_data
def render_figure(lead, name):
    """
    This function was generated by Sonnet 4.6
    """
    SAMPLING_RATE = 400
    fig = go.Figure()
    t = [i / SAMPLING_RATE for i in range(len(lead))]
    fig.add_trace(go.Scatter(
        x=t,
        y=lead,
        mode="lines",
        line=dict(color="#00ff88", width=1.2),
    ))
    fig.update_layout(
        title=dict(text=name, font=dict(color="white")),
        xaxis_title="Time (s)",
        yaxis_title="Amplitude (mV)",
        plot_bgcolor="#0e1117",
        paper_bgcolor="#0e1117",
        font_color="white",
        xaxis=dict(showgrid=True, gridcolor="#1f2937", zeroline=False),
        yaxis=dict(showgrid=True, gridcolor="#1f2937", zeroline=False),
        height=300,
        margin=dict(l=40, r=20, t=40, b=40),
    )
    return fig

def set_comparison(idx):
    st.session_state.comparison_index = idx

@st.cache_data
def fetch_page(index: int):
    return pd.read_parquet(f"data/{index}.parquet", engine="pyarrow")

@st.fragment
def comparison_per_signal():
    signals = fetch_page(st.session_state.page_index)
    
    original = signals.iloc[0]
    comp = {1: signals.iloc[1], 2: signals.iloc[2], 3: signals.iloc[3]}[st.session_state.comparison_index]

    _, col1, col2, col3, _ = st.columns([2, 1, 1, 1, 2])
    with col1:
        st.button("Comparison 1", type="primary" if st.session_state.comparison_index == 1 else "secondary",
                  on_click=set_comparison, args=(1,), use_container_width=True)
    with col2:
        st.button("Comparison 2", type="primary" if st.session_state.comparison_index == 2 else "secondary",
                  on_click=set_comparison, args=(2,), use_container_width=True)
    with col3:
        st.button("Comparison 3", type="primary" if st.session_state.comparison_index == 3 else "secondary",
                  on_click=set_comparison, args=(3,), use_container_width=True)

    st.divider()

    for lead, name in zip(LEADS, LEAD_NAMES):
        st.markdown(f"**{name}**")
        col_left, col_right = st.columns(2)
        with col_left:
            st.plotly_chart(render_figure(original[lead], "Original"), use_container_width=True, key=f"{lead}_orig")
        with col_right:
            st.plotly_chart(render_figure(comp[lead], f"Comparison {st.session_state.comparison_index}"), use_container_width=True, key=f"{lead}_comp{st.session_state.comparison_index}")


