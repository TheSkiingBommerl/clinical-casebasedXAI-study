@st.fragment
def display_lead(name, on, lead, original, comp_1, comp_2, comp_3):
    with st.expander(name, expanded=True): 
        st.markdown('<div class="content-box">', unsafe_allow_html=True)
        if on:
            st.plotly_chart(render_figure(original[lead], "Original"), use_container_width=True, key=f"{lead}_orig")
            st.plotly_chart(render_figure(comp_1[lead], f"Comparison 1"), use_container_width=True, key=f"{lead}_comp1")
            st.plotly_chart(render_figure(comp_2[lead], f"Comparison 2"), use_container_width=True, key=f"{lead}_comp2")
            st.plotly_chart(render_figure(comp_3[lead], f"Comparison 3"), use_container_width=True, key=f"{lead}_comp3")
        
        else:
            col1, col2 = st.columns([1, 1])
            with col1:
                st.plotly_chart(render_figure(original[lead], "Original"), use_container_width=True, key=f"{lead}_orig")
                st.plotly_chart(render_figure(comp_2[lead], f"Comparison 2"), use_container_width=True, key=f"{lead}_comp2")
            with col2:
                st.plotly_chart(render_figure(comp_1[lead], f"Comparison 1"), use_container_width=True, key=f"{lead}_comp1")
                st.plotly_chart(render_figure(comp_3[lead], f"Comparison 3"), use_container_width=True, key=f"{lead}_comp3")

def save_selection(lead):
    st.session_state[f"saved_{lead}"] = st.session_state[f"lead_{lead}_{st.session_state.page_index}"]

@st.fragment
def display_lead_selection(name, lead):
    """
    This function was generated by Sonnet 4.6
    """
    st.markdown("""
    <style>
        div[data-testid="stElementContainer"][class*="st-key-lead_"] {
            width: 100% !important;
            display: flex !important;
            justify-content: center !important;
        }
        div[data-testid="stButtonGroup"] button {
            padding: 0.75rem 2rem !important;
            height: auto !important;
        }
        </style>
    """, unsafe_allow_html=True)
    
  
    text = f"<b> Which comparison signal is most similar to the original signal for lead {name} </b>"
    st.markdown(f'<p style="font-size: 20px; text-align: center;">{text}</p>', unsafe_allow_html=True)
    st.segmented_control(
        "",
        options=["Comparison 1", "Comparison 2", "Comparison 3"],
        key=f"lead_{lead}_{st.session_state.page_index}",
        on_change=save_selection,
        args=(lead,)
    )

@st.fragment
def display_summary():
    """
    This function was generated by Sonnet 4.6
    """
    counts = Counter(
        st.session_state.get(f"saved_{lead}")
        for lead in LEADS
        if st.session_state.get(f"saved_{lead}") is not None
    )
    st.write("Press the 'Refresh Summary' button to see how often each comparison signal was the most similar to the original signal.")
    col_1, col3 = st.columns([1,2])
    with col_1:
        if st.button("Refresh Summary", help="Click to get the updated counts"):
            total = sum(counts.values())
            if total < len(LEADS):
                st.warning(f"Only {total} out of {len(LEADS)} leads have been selected.")

    with col3:
        st.dataframe(
            {"ECG": ["Comparison 1", "Comparison 2", "Comparison 3"],
            "Count": [counts.get(comp, 0) for comp in ["Comparison 1", "Comparison 2", "Comparison 3"]]},
            hide_index=True,
            use_container_width=True
        )

def comparison_per_lead():

    on = st.toggle("Detailed View")

    st.divider()

    expender_style()
        
    signals = fetch_page(st.session_state.page_index)
    original = signals.iloc[0]
    comp_1 = signals.iloc[1]
    comp_2 = signals.iloc[2]
    comp_3 = signals.iloc[3]

    
    for lead, name in zip(LEADS, LEAD_NAMES):
        display_lead(name, on, lead, original, comp_1, comp_2, comp_3)
        display_lead_selection(name, lead)


